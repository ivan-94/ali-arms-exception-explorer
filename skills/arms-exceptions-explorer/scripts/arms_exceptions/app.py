def friendly_argparse_error(message: str) -> str:
    ambiguous = re.match(r"ambiguous option: (\S+) could match (.+)", message)
    if ambiguous:
        option = ambiguous.group(1)
        matches = ambiguous.group(2)
        return f"参数 {option} 不明确，可匹配 {matches}。请写完整参数名。"

    unrecognized = re.match(r"unrecognized arguments?: (.+)", message)
    if unrecognized:
        return f"无法识别参数: {unrecognized.group(1)}。请检查参数名是否拼写完整。"

    required = re.match(r"the following arguments are required: (.+)", message)
    if required:
        return f"缺少必需参数: {required.group(1)}。"

    invalid_choice = re.match(r"argument (\S+): invalid choice: (.+)", message)
    if invalid_choice:
        value, choices = split_invalid_choice_detail(invalid_choice.group(2))
        if invalid_choice.group(1) == "command":
            return f"未知命令: {value}。可用命令: {choices}。"
        return f"参数 {invalid_choice.group(1)} 的取值无效: {value}。可选值: {choices}。"

    invalid_choice_positional = re.match(r"invalid choice: (.+)", message)
    if invalid_choice_positional:
        value, choices = split_invalid_choice_detail(invalid_choice_positional.group(1))
        return f"未知命令或取值无效: {value}。可选值: {choices}。"

    conflict = re.match(r"argument (\S+): not allowed with argument (\S+)", message)
    if conflict:
        return f"参数 {conflict.group(1)} 不能和 {conflict.group(2)} 同时使用。"

    expected = re.match(r"argument (\S+): expected one argument", message)
    if expected:
        return f"参数 {expected.group(1)} 需要一个值。"

    invalid_value = re.match(r"argument (\S+): invalid (.+) value: (.+)", message)
    if invalid_value:
        return f"参数 {invalid_value.group(1)} 的值无效: {invalid_value.group(3)}。"

    return message


def split_invalid_choice_detail(detail: str) -> tuple[str, str]:
    match = re.match(r"(.+?) \(choose from (.+)\)", detail)
    if match:
        return match.group(1), match.group(2)
    return detail, "见完整帮助"


def _sanitize_command(args: Sequence[str]) -> str:
    return " ".join(_sanitize(str(arg)) for arg in args)


def _sanitize(value: str) -> str:
    text = value
    sensitive_keys = [
        "AccessKeyId",
        "AccessKeySecret",
        "SecurityToken",
        "Signature",
        "SignatureNonce",
        "Authorization",
        "Credential",
        "code",
    ]
    for key in sensitive_keys:
        text = re.sub(rf"({key}=)[^&\s]+", rf"\1<redacted>", text, flags=re.IGNORECASE)
        text = re.sub(rf'("{key}"\s*:\s*")[^"]+', rf'\1<redacted>', text, flags=re.IGNORECASE)
        text = re.sub(rf"({key}:)\s*[^\s,]+", rf"\1 <redacted>", text, flags=re.IGNORECASE)
    text = re.sub(r"(Authorization:\s*)[^\n\r]+", r"\1<redacted>", text, flags=re.IGNORECASE)
    text = re.sub(r"(Credential=)[^,\s]+", r"\1<redacted>", text, flags=re.IGNORECASE)
    return text


