def spans_from_get_trace_response(response: dict[str, Any], *, trace_id: str) -> list[SpanRecord]:
    raw_spans: Any = response.get("Spans") or response.get("Span") or []
    if isinstance(raw_spans, dict):
        raw_spans = raw_spans.get("Span") or raw_spans.get("Spans") or []
    if not isinstance(raw_spans, list):
        return []

    spans: list[SpanRecord] = []
    for item in raw_spans:
        if not isinstance(item, dict):
            continue
        span_id = item.get("SpanId") or item.get("SpanID") or item.get("spanId")
        if not span_id:
            continue
        tags = extract_tags(item)
        spans.append(
            SpanRecord(
                trace_id=str(item.get("TraceID") or item.get("TraceId") or trace_id),
                span_id=str(span_id),
                parent_span_id=_optional_str(item.get("ParentSpanId") or item.get("ParentSpanID")),
                service_name=str(item.get("ServiceName") or tags.get("service.name") or ""),
                operation_name=str(item.get("OperationName") or tags.get("rpc") or ""),
                result_code=_optional_str(item.get("ResultCode") or item.get("StatusCode")),
                timestamp_ms=_optional_int(item.get("Timestamp")),
                duration_ms=_optional_int(item.get("Duration")),
                service_ip=_optional_str(item.get("ServiceIp") or item.get("ServiceIP")),
                tags=tags,
                raw=item,
            )
        )
    return spans


def extract_tags(item: dict[str, Any]) -> dict[str, str]:
    tags: dict[str, str] = {}
    for key in ("TagEntryList", "Tags", "tagEntryList"):
        entries = item.get(key)
        if not entries:
            continue
        if isinstance(entries, dict):
            entries = entries.get("TagEntry") or entries.get("Tags") or entries.get("TagEntries") or []
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            tag_key = entry.get("Key") or entry.get("key")
            if not tag_key:
                continue
            value = entry.get("Value") if "Value" in entry else entry.get("value")
            tags[str(tag_key)] = "" if value is None else str(value)
    return tags


def is_error_span(span: SpanRecord, expected_span_ids: set[str] | None = None) -> bool:
    if expected_span_ids and span.span_id in expected_span_ids:
        return True
    tags = span.tags
    if first_present(tags, "exception.type", "exception.message", "exception.stacktrace"):
        return True
    if first_present(tags, "error.capture.source", "error.type", "error.message"):
        return True
    if first_present(tags, "celery.exception_type", "celery.einfo"):
        return True
    if first_present(tags, "log.level") == "ERROR":
        return True
    status_code = first_present(tags, "statusCode", "http.status_code", "http.response.status_code", "status")
    if status_code:
        try:
            return int(status_code) >= 400
        except ValueError:
            return status_code.lower() in {"error", "failure", "failed"}
    return False


def error_events_from_span(span: SpanRecord, expected_span_ids: set[str] | None = None) -> list[ErrorEvent]:
    events: list[ErrorEvent] = []
    raw_events = span.raw.get("LogEventList") or []
    if isinstance(raw_events, dict):
        raw_events = raw_events.get("LogEvent") or raw_events.get("LogEvents") or []
    if isinstance(raw_events, list):
        for index, raw_event in enumerate(raw_events):
            if not isinstance(raw_event, dict):
                continue
            tags = extract_tags(raw_event)
            if not _tags_describe_error(tags):
                continue
            timestamp_ms = _optional_int(raw_event.get("Timestamp")) or span.timestamp_ms
            events.append(_event_from_tags(span, tags, event_index=index, timestamp_ms=timestamp_ms))

    if is_error_span(span, expected_span_ids):
        top_tags = span.tags
        if not events or _has_top_level_only_error(top_tags):
            events.append(_event_from_tags(span, top_tags, event_index=None, timestamp_ms=span.timestamp_ms))
    return _dedupe_events(events)


def _event_from_tags(
    span: SpanRecord,
    tags: dict[str, str],
    *,
    event_index: int | None,
    timestamp_ms: int | None,
) -> ErrorEvent:
    stacktrace = first_present(tags, "exception.stacktrace", "celery.einfo", "error.stack", "stacktrace", "traceback")
    fingerprint = fingerprint_from_tags(
        service_name=span.service_name,
        operation_name=span.operation_name,
        tags=tags,
        fallback_message=span.operation_name or "unknown",
    )
    source = first_present(tags, "error.capture.source", "otel.scope.name", "component") or "unknown"
    return ErrorEvent(
        trace_id=span.trace_id,
        span_id=span.span_id,
        event_index=event_index,
        timestamp_ms=timestamp_ms,
        service_name=span.service_name,
        operation_name=span.operation_name,
        source=source,
        exception_type=fingerprint.exception_type,
        message=fingerprint.message,
        stacktrace=stacktrace,
        top_stack_frame=fingerprint.top_stack_frame,
        code_filepath=fingerprint.code_filepath,
        code_function=fingerprint.code_function,
        code_lineno=fingerprint.code_lineno,
        log_original=first_present(tags, "log.original"),
        is_handled=first_present(tags, "error.capture.handled"),
        is_synthetic=first_present(tags, "error.synthetic"),
        raw_tags=tags,
        fingerprint=fingerprint,
    )


def fingerprint_from_tags(
    *,
    service_name: str,
    operation_name: str,
    tags: dict[str, str],
    fallback_message: str,
) -> ErrorFingerprint:
    exception_type = first_present(tags, "exception.type", "celery.exception_type", "error.type", "error.kind", "llm.error.type")
    if not exception_type:
        status_code = first_present(tags, "http.status_code", "http.response.status_code", "statusCode", "status")
        exception_type = f"http.{status_code}" if status_code else "unknown"

    raw_message = first_present(
        tags,
        "exception.message",
        "error.message",
        "llm.error.message",
        "status.message",
        "StatusMessage",
        "celery.einfo",
        "log.message",
        "log.original",
    ) or fallback_message
    message = normalize_message(raw_message)
    stacktrace = first_present(tags, "exception.stacktrace", "celery.einfo", "error.stack", "stacktrace", "traceback")
    top_stack_frame = extract_top_stack_frame(stacktrace)
    code_filepath = first_present(tags, "code.filepath", "code.file", "code.namespace")
    code_function = first_present(tags, "code.function")
    code_lineno = first_present(tags, "code.lineno")
    if not top_stack_frame and code_filepath:
        top_stack_frame = f"{code_filepath}:{code_function or ''}".rstrip(":")
    source = first_present(tags, "error.capture.source", "otel.scope.name", "component")
    digest = hashlib.sha1("\n".join([service_name, exception_type, message, top_stack_frame or ""]).encode("utf-8")).hexdigest()[:16]
    return ErrorFingerprint(
        key=digest,
        service_name=service_name,
        exception_type=exception_type,
        message=message,
        top_stack_frame=top_stack_frame,
        source=source,
        code_filepath=code_filepath,
        code_function=code_function,
        code_lineno=code_lineno,
    )


def _tags_describe_error(tags: dict[str, str]) -> bool:
    if first_present(tags, "exception.type", "exception.message", "exception.stacktrace"):
        return True
    if first_present(tags, "celery.exception_type", "celery.einfo"):
        return True
    if first_present(tags, "llm.error.type", "llm.error.message"):
        return True
    if first_present(tags, "error.capture.source", "error.message", "error.type"):
        return True
    if first_present(tags, "log.level") == "ERROR":
        return True
    status_code = first_present(tags, "http.status_code", "http.response.status_code", "statusCode", "status")
    if status_code:
        try:
            return int(status_code) >= 400
        except ValueError:
            return status_code.lower() in {"error", "failure", "failed"}
    return False


def _has_top_level_only_error(tags: dict[str, str]) -> bool:
    return bool(
        first_present(tags, "celery.einfo", "llm.error.message")
        or (
            first_present(tags, "http.status_code", "http.response.status_code", "statusCode", "status")
            and not first_present(tags, "error.capture.source")
        )
    )


def _dedupe_events(events: list[ErrorEvent]) -> list[ErrorEvent]:
    seen: set[tuple[str, str, str | None]] = set()
    unique: list[ErrorEvent] = []
    for event in events:
        key = (event.exception_type, event.message, event.top_stack_frame)
        if key in seen:
            continue
        seen.add(key)
        unique.append(event)
    return unique


def first_present(tags: dict[str, str], *keys: str) -> str | None:
    for key in keys:
        value = tags.get(key)
        if value:
            return value
    return None


def normalize_message(message: str, *, max_length: int = 500) -> str:
    text = message.strip()
    if "\n" in text or "Traceback " in text:
        text = _last_exception_line(text)
    text = re.sub(r"0x[0-9a-fA-F]+", "0x<hex>", text)
    text = re.sub(r"\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b", "<uuid>", text)
    text = re.sub(r"\b[0-9a-fA-F]{24,}\b", "<hex-id>", text)
    text = re.sub(r"\b\d{13,}\b", "<long-number>", text)
    text = re.sub(r"(https?://[^\s?]+)\?[^\s]+", r"\1?<query>", text)
    text = re.sub(r"([?&](?:traceId|trace_id|spanId|span_id|requestId|request_id|id)=)[^&\s]+", r"\1<id>", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:max_length]


def _last_exception_line(text: str) -> str:
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    for line in reversed(lines):
        if re.match(r"^[\w.]+(?:Error|Exception|HTTPException|Warning)\b", line):
            return line
        if ": " in line and not line.startswith("File "):
            return line
    return lines[-1] if lines else text


def extract_top_stack_frame(stacktrace: str | None) -> str | None:
    if not stacktrace:
        return None
    frames: list[tuple[str, str]] = []
    pattern = re.compile(r'File "([^"]+)", line \d+, in ([^\s]+)')
    for line in stacktrace.splitlines():
        match = pattern.search(line)
        if not match:
            continue
        path, function = match.group(1), match.group(2)
        frames.append((path, function))
    for path, function in reversed(frames):
        if _is_noisy_frame(path):
            continue
        return f"{path}:{function}"
    if frames:
        path, function = frames[-1]
        return f"{path}:{function}"
    return None


def _is_noisy_frame(path: str) -> bool:
    noisy_parts = (
        "site-packages/opentelemetry",
        "site-packages/aliyun",
        "site-packages/celery",
        "site-packages/kombu",
        "site-packages/billiard",
        "site-packages/starlette",
        "site-packages/fastapi",
        "site-packages/uvicorn",
    )
    return any(part in path for part in noisy_parts)


def resolve_sync_time_range(
    args: argparse.Namespace,
    *,
    config: ProjectConfig,
    target: TargetConfig | None,
) -> tuple[int, int]:
    if args.start or args.end:
        if not args.start or not args.end:
            raise UserFacingError(
                "错误: --start 和 --end 必须成对出现。\n\n"
                "下一步:\n"
                f"  {script_name()} sync --target <target> --start \"2026-06-01 00:00:00\" --end \"2026-06-02 00:00:00\""
            )
        start = parse_local_datetime(args.start, args.timezone)
        end = parse_local_datetime(args.end, args.timezone)
        if end <= start:
            raise UserFacingError(
                "错误: --end 必须晚于 --start。\n\n"
                "下一步:\n"
                f"  {script_name()} sync --target <target> --start \"2026-06-01 00:00:00\" --end \"2026-06-02 00:00:00\""
            )
        return to_epoch_ms(start), to_epoch_ms(end)
    window = args.window or (target.default_window if target else None) or config.default_window or DEFAULT_WINDOW
    return resolve_window_ms(window, tz_name=args.timezone)


def resolve_window_ms(window: str, *, tz_name: str = DEFAULT_TZ) -> tuple[int, int]:
    now = datetime.now(ZoneInfo(tz_name))
    delta = parse_window(window)
    start = now - delta
    return to_epoch_ms(start), to_epoch_ms(now)


def parse_window(value: str) -> timedelta:
    match = re.fullmatch(r"\s*(\d+)\s*([mhd])\s*", value)
    if not match:
        raise UserFacingError(
            f"错误: 无法解析窗口: {value!r}\n\n"
            "下一步:\n"
            f"  {script_name()} sync --target <target> --window 24h"
        )
    amount = int(match.group(1))
    unit = match.group(2)
    if unit == "m":
        return timedelta(minutes=amount)
    if unit == "h":
        return timedelta(hours=amount)
    return timedelta(days=amount)


def parse_local_datetime(value: str, tz_name: str = DEFAULT_TZ) -> datetime:
    text = value.strip()
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d"):
        try:
            parsed = datetime.strptime(text, fmt)
            return parsed.replace(tzinfo=ZoneInfo(tz_name))
        except ValueError:
            continue
    raise UserFacingError(
        f"错误: 无法解析时间: {value!r}\n\n"
        "下一步:\n"
        "  使用格式: 2026-06-02 00:00:00\n"
        f"  {script_name()} sync --target <target> --start \"2026-06-01 00:00:00\" --end \"2026-06-02 00:00:00\""
    )


def parse_optional_time(value: str | None, tz_name: str) -> int | None:
    if not value:
        return None
    return to_epoch_ms(parse_local_datetime(value, tz_name))


def to_epoch_ms(value: datetime) -> int:
    if value.tzinfo is None:
        raise ValueError("datetime 必须包含时区")
    return int(value.astimezone(timezone.utc).timestamp() * 1000)


def format_epoch_ms(value: int, tz_name: str = DEFAULT_TZ) -> str:
    return datetime.fromtimestamp(value / 1000, ZoneInfo(tz_name)).strftime("%Y-%m-%d %H:%M:%S")


def _scope_where(
    table: str,
    *,
    target_name: str | None,
    service_names: Sequence[str] | None,
) -> tuple[list[str], list[Any]]:
    where: list[str] = []
    values: list[Any] = []
    if target_name:
        where.append(f"{table}.target_name = ?")
        values.append(target_name)
    if service_names:
        placeholders = ",".join(["?"] * len(service_names))
        where.append(f"{table}.service_name in ({placeholders})")
        values.extend(service_names)
    return where, values


