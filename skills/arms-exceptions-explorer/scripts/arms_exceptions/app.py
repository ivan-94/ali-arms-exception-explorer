def cmd_sync(args: argparse.Namespace) -> int:
    config = ProjectConfig.load(args.config)
    target, services = resolve_scope(args, config, command_name="sync")
    start_ms, end_ms = resolve_sync_time_range(args, config=config, target=target)
    repository = TraceRepository(args.db)
    client = build_client()
    failures: list[tuple[ServiceConfig, str]] = []
    summaries: list[SyncSummary] = []
    try:
        service = TraceIngestionService(client=client, repository=repository)
        for service_config in services:
            try:
                summary = service.sync_errors(
                    SyncOptions(
                        target_name=target.name if target else None,
                        service=service_config,
                        start_ms=start_ms,
                        end_ms=end_ms,
                        operation_name=args.operation,
                        page_size=args.page_size,
                        max_pages=args.max_pages,
                        max_traces=args.max_traces,
                        trace_page_size=args.trace_page_size,
                        max_trace_pages=args.max_trace_pages,
                    )
                )
                summaries.append(summary)
            except Exception as exc:
                failures.append((service_config, _sanitize(str(exc))))
    finally:
        repository.close()

    payload = {
        "range": {"start_ms": start_ms, "end_ms": end_ms, "start": format_epoch_ms(start_ms), "end": format_epoch_ms(end_ms)},
        "summaries": [sync_summary_to_dict(summary) for summary in summaries],
        "failures": [{"service": service.name, "error": error} for service, error in failures],
    }
    if getattr(args, "json_output", False):
        print(_json(payload))
    else:
        print(f"range: {format_epoch_ms(start_ms)} -> {format_epoch_ms(end_ms)}")
        for summary in summaries:
            print()
            print(f"service: {summary.service_name}")
            print(f"sync_run: {summary.run_id}")
            print(f"total: {summary.total}")
            print(f"trace_infos: {summary.trace_infos}")
            print(f"unique_traces: {summary.unique_traces}")
            print(f"fetched_traces: {summary.fetched_traces}")
            print(f"stored_spans: {summary.stored_spans}")
            print(f"error_events: {summary.error_events}")
        for service_config, error in failures:
            print()
            print(f"失败 service: {service_config.name}", file=sys.stderr)
            print(error, file=sys.stderr)
            print("下一步:", file=sys.stderr)
            print(f"  {script_name()} sync --service {service_config.name}", file=sys.stderr)
    return 1 if failures else 0


