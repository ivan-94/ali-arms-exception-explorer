def cmd_init_interactive(args: argparse.Namespace) -> int:
    client = build_client()
    region = _prompt("region", args.region or DEFAULT_REGION)
    search = _prompt("search apps", "")
    apps = client.list_trace_apps(region=region, search=search or None)
    if not apps:
        raise UserFacingError(
            "错误: 未找到可选择的 ARMS TRACE 应用。\n\n"
            "下一步:\n"
            f"  {script_name()} apps --region {region}\n"
            "  aliyun configure get"
        )
    for index, app in enumerate(apps, 1):
        print(f"{index}. {app.name} ({app.region})")
    indexes_text = _prompt("service indexes, comma separated", "1")
    selected = _select_apps(apps, indexes_text)
    target_name = _prompt("target name", selected[0].name if selected else "")
    branch = _prompt("branch", "")
    window = _prompt("default window", DEFAULT_WINDOW)
    config = ProjectConfig.load(args.config)
    replace = False
    if config.get_target(target_name):
        answer = _prompt("target exists: merge, replace, cancel", "merge").lower()
        if answer.startswith("c"):
            print("已取消")
            return 0
        replace = answer.startswith("r")
    config.add_or_update_target(
        target_name=target_name,
        branch=branch or None,
        default_window=window,
        services=[app_to_service(app) for app in selected],
        replace=replace,
    )
    config.save(args.config)
    print(f"已写入配置: {args.config}")
    print(f"已更新忽略文件: {args.config.parent / '.gitignore'}")
    print("下一步:")
    print(f"  {script_name()} targets")
    print(f"  {script_name()} sync --target {target_name}")
    return 0


