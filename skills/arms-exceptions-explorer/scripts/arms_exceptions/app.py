def cmd_show(args: argparse.Namespace) -> int:
    config = ProjectConfig.load(args.config)
    repository = TraceRepository(args.db)
    try:
        target: TargetConfig | None = None
        services: list[ServiceConfig] = []
        if args.target or args.service:
            target, services = resolve_scope(args, config, command_name="show")
            group = repository.get_group(
                args.group_id,
                target_name=target.name if target else None,
                service_names=[service.name for service in services],
            )
            if not group:
                raise UserFacingError(format_show_group_not_found(args.group_id, config, target=target, services=services))
        else:
            groups = repository.list_groups_by_key(args.group_id, limit=2)
            if not groups:
                raise UserFacingError(format_show_group_not_found(args.group_id, config))
            if len(groups) > 1:
                raise UserFacingError(format_show_group_ambiguous(args.group_id, groups))
            group = groups[0]
        occurrences = repository.list_group_occurrences(args.group_id, limit=args.limit)
        events = repository.list_group_events(args.group_id, limit=args.limit)
        sample_event = repository.get_event(group["sample_event_id"])
        sample_span = repository.get_span(group["sample_trace_id"], group["sample_span_id"])
    finally:
        repository.close()

    if getattr(args, "json_output", False):
        payload = {
            "group": row_to_dict(group),
            "occurrences": [row_to_dict(row) for row in occurrences],
            "events": [_event_row_to_payload(row, raw=args.raw_event) for row in events],
            "sample_event": _event_row_to_payload(sample_event, raw=args.raw_event) if sample_event else None,
            "sample_span": _span_row_to_payload(sample_span, raw=args.raw_span) if sample_span else None,
        }
        print(_json(payload))
        return 0

    print(f"group_id: {group['group_key']}")
    print(f"target: {group['target_name'] or ''}")
    print(f"service: {group['service_name']}")
    print(f"operation: {group['operation_name']}")
    print(f"exception_type: {group['exception_type']}")
    print(f"message: {group['message']}")
    print(f"top_stack_frame: {group['top_stack_frame'] or ''}")
    print(f"source: {group['source'] or ''}")
    print(f"count: {group['occurrence_count']}")
    print(f"first_seen: {format_epoch_ms(group['first_seen_ms']) if group['first_seen_ms'] else ''}")
    print(f"last_seen: {format_epoch_ms(group['last_seen_ms']) if group['last_seen_ms'] else ''}")
    print(f"sample_trace_id: {group['sample_trace_id'] or ''}")
    print(f"sample_span_id: {group['sample_span_id'] or ''}")
    print()
    print("occurrences:")
    for row in occurrences:
        print(
            f"- {format_epoch_ms(row['timestamp_ms']) if row['timestamp_ms'] else ''} "
            f"trace={row['trace_id']} span={row['span_id']} "
            f"event={_format_event_index(row['event_index'])} "
            f"service={row['service_name']} operation={row['operation_name']}"
        )
    if events:
        print()
        print("error_events:")
        for row in events:
            print(
                f"- event={_format_event_index(row['event_index'])} "
                f"type={row['exception_type']} source={row['source']} "
                f"message={_truncate(row['message'], 180)}"
            )
    if sample_event:
        print()
        print("error_detail:")
        print(f"type: {sample_event['exception_type']}")
        print(f"message: {sample_event['message']}")
        print(f"source: {sample_event['source']}")
        if sample_event["top_stack_frame"]:
            print(f"top_stack_frame: {sample_event['top_stack_frame']}")
        code = _format_event_code(sample_event)
        if code:
            print(f"code: {code}")
        if sample_event["stacktrace"]:
            print()
            print("stacktrace:")
            print(sample_event["stacktrace"])
    if sample_span:
        print()
        print("sample_tags:")
        tags = json.loads(sample_span["tags_json"])
        for key in sorted(tags):
            value = str(tags[key]).replace("\n", "\\n")
            print(f"  {key}: {_truncate(value, 240)}")
    if args.raw_event and sample_event:
        print()
        print("raw_event:")
        print(_json(json.loads(sample_event["raw_tags_json"])))
    if args.raw_span and sample_span:
        print()
        print("raw_span:")
        print(_json(json.loads(sample_span["raw_json"])))
    return 0


def format_show_group_not_found(
    group_id: str,
    config: ProjectConfig,
    *,
    target: TargetConfig | None = None,
    services: Sequence[ServiceConfig] | None = None,
) -> str:
    lines = [
        f"错误: 未找到异常组: {group_id}",
        "",
        "说明:",
        "  show 会在本地 SQLite 中按 group_id 精确查找；查不到通常表示还没有同步，或 group_id 来自其他 target/service。",
        "",
        "下一步:",
    ]
    if target:
        lines.append(f"  {script_name()} groups --target {target.name}")
        lines.append(f"  {script_name()} sync --target {target.name}")
    elif services:
        service = services[0]
        lines.append(f"  {script_name()} groups --service {service.name}")
        lines.append(f"  {script_name()} sync --service {service.name}")
    elif config.targets:
        first_target = config.targets[0]
        lines.append(f"  {script_name()} groups --target {first_target.name}")
        lines.append(f"  {script_name()} sync --target {first_target.name}")
        lines.append(f"  {script_name()} targets")
    else:
        lines.append(f"  {script_name()} init")
        lines.append(f"  {script_name()} targets")
    return "\n".join(lines)


def format_show_group_ambiguous(group_id: str, groups: Sequence[sqlite3.Row]) -> str:
    lines = [
        f"错误: 异常组 {group_id} 命中多个 target/service，请指定 --target 或 --service。",
        "",
        "命中范围:",
    ]
    for group in groups:
        lines.append(f"- target={group['target_name'] or '-'} service={group['service_name']}")
    lines.extend(
        [
            "",
            "下一步:",
            f"  {script_name()} show {group_id} --target <target>",
            f"  {script_name()} show {group_id} --service <service>",
            f"  {script_name()} targets",
        ]
    )
    return "\n".join(lines)


def resolve_scope(args: argparse.Namespace, config: ProjectConfig, *, command_name: str) -> tuple[TargetConfig | None, list[ServiceConfig]]:
    if not args.target and not args.service:
        raise UserFacingError(
            f"错误: {command_name} 需要指定 --target 或 --service。\n\n"
            + format_available_scopes(config)
            + "\n下一步:\n"
            f"  {script_name()} {command_name} --target <target>\n"
            f"  {script_name()} targets"
        )
    if args.target:
        target = config.get_target(args.target)
        if not target:
            raise UserFacingError(
                f"错误: 未找到 target: {args.target}\n\n"
                + format_available_scopes(config)
                + "\n下一步:\n"
                f"  {script_name()} targets\n"
                f"  {script_name()} init"
            )
        if not target.services:
            raise UserFacingError(
                f"错误: target 没有配置 service: {target.name}\n\n"
                "下一步:\n"
                f"  {script_name()} init --target {target.name} --service <service>"
            )
        return target, list(target.services)
    target, service = config.find_service(args.service)
    if not service:
        raise UserFacingError(
            f"错误: 未找到 service: {args.service}\n\n"
            + format_available_scopes(config)
            + "\n下一步:\n"
            f"  {script_name()} targets\n"
            f"  {script_name()} init --target <target> --service {args.service}"
        )
    return target, [service]


def format_available_scopes(config: ProjectConfig) -> str:
    if not config.targets:
        return (
            "当前没有配置 target/service。\n\n"
            "下一步:\n"
            f"  {script_name()} init\n"
            f"  {script_name()} apps --region {DEFAULT_REGION} --search ai-service\n"
        )
    lines = ["可用 target:"]
    for target in config.targets:
        lines.append(f"- {target.name}")
    lines.append("")
    lines.append("可用 service:")
    for service in config.list_services():
        lines.append(f"- {service.name}")
    lines.append("")
    return "\n".join(lines)


def resolve_services_from_apps(
    client: AliyunCliClient,
    *,
    service_names: Sequence[str],
    region: str,
) -> list[ServiceConfig]:
    unique_names = list(dict.fromkeys(service_names))
    apps = client.list_trace_apps(region=region, search=None)
    by_name = {app.name: app for app in apps}
    missing = [name for name in unique_names if name not in by_name]
    if missing:
        missing_text = ", ".join(missing)
        raise UserFacingError(
            f"错误: service 不在当前 ARMS TRACE 应用列表中: {missing_text}\n\n"
            "下一步:\n"
            f"  {script_name()} apps --region {region} --search {missing[0]}\n"
            "  确认当前 aliyun 默认账号是否能访问该应用"
        )
    return [app_to_service(by_name[name]) for name in unique_names]


