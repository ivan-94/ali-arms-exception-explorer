def _event_row_to_payload(row: sqlite3.Row | None, *, raw: bool = False) -> dict[str, Any] | None:
    if row is None:
        return None
    payload = row_to_dict(row)
    if raw:
        payload["raw_tags"] = json.loads(row["raw_tags_json"])
    payload.pop("raw_tags_json", None)
    return payload


def _span_row_to_payload(row: sqlite3.Row | None, *, raw: bool = False) -> dict[str, Any] | None:
    if row is None:
        return None
    payload = row_to_dict(row)
    payload["tags"] = json.loads(row["tags_json"])
    payload.pop("tags_json", None)
    if raw:
        payload["raw"] = json.loads(row["raw_json"])
    payload.pop("raw_json", None)
    return payload


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _optional_str(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value)
    return text if text else None


def _optional_int(value: Any) -> int | None:
    if value is None or value == "":
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _first_nonempty(*values: Any) -> str | None:
    for value in values:
        if value is None:
            continue
        text = str(value)
        if text:
            return text
    return None


def _format_row(values: Sequence[str], widths: Sequence[int]) -> str:
    cells = []
    for value, width in zip(values, widths):
        cells.append(_truncate(str(value), width).ljust(width))
    return "  ".join(cells)


def _truncate(value: str, width: int) -> str:
    if len(value) <= width:
        return value
    if width <= 1:
        return value[:width]
    return value[: width - 1] + "…"


def _format_event_index(value: object) -> str:
    if value is None or value == -1:
        return "-"
    return str(value)


def _format_event_code(row: sqlite3.Row) -> str:
    filepath = row["code_filepath"] or ""
    function = row["code_function"] or ""
    lineno = row["code_lineno"] or ""
    if not any((filepath, function, lineno)):
        return ""
    return f"{filepath}:{lineno} {function}".strip()


def _prompt(label: str, default: str) -> str:
    suffix = f" [{default}]" if default else ""
    value = input(f"{label}{suffix}: ").strip()
    return value or default


def _select_apps(apps: Sequence[AppInfo], indexes_text: str) -> list[AppInfo]:
    selected: list[AppInfo] = []
    for part in indexes_text.split(","):
        part = part.strip()
        if not part:
            continue
        try:
            index = int(part)
        except ValueError:
            continue
        if 1 <= index <= len(apps):
            selected.append(apps[index - 1])
    if not selected:
        raise UserFacingError(
            "错误: 没有选择任何 service。\n\n"
            "下一步:\n"
            "  重新执行 init，并输入应用序号，例如: 1,2"
        )
    return selected


